// Turns tools/cardtest.js results into src/cardpower.js (measured win-rate change per copy vs. a potion + free quest).
// node tools/cardtest.js 50 0 2 & node tools/cardtest.js 50 1 2 ; node tools/make_cardpower.js
const fs = require('fs');
const R = {}; for (const f of fs.readdirSync('/tmp/m').filter(f => /^cardtest_\d+\.json$/.test(f))) Object.assign(R, JSON.parse(fs.readFileSync('/tmp/m/' + f)).res);
const out = {};
for (const [id, x] of Object.entries(R)) {
  const by = { crypt: [], molten: [], tide: [] };
  for (const [k, v] of Object.entries(x.per)) by[k.split('/')[1]].push(v);
  const m = a => a.length ? +(a.reduce((s, y) => s + y, 0) / a.length).toFixed(1) : 0;
  out[id] = [x.dWin, m(by.crypt), m(by.molten), m(by.tide)];
}
const keys = Object.keys(out).sort();
const body = keys.map(k => `${JSON.stringify(k)}:[${out[k].join(',')}]`).join(',');
fs.writeFileSync(__dirname + '/../src/cardpower.js', `/* RAIDBOUND — measured card power (generated by tools/make_cardpower.js from tools/cardtest.js; do not edit by hand).
   Win-rate change per copy versus a Healing Draught / free quest in starter decks (added, or removed when the starter
   already has it), solo raids: Crypt and Molten Spire on Heroic, Sunken Cathedral on Normal. [average, crypt, molten, tide]. Used by deck builders. */
(function (RB) { RB.CARD_POWER = {${body}}; })(globalThis.RB);\n`);
console.log('cards', keys.length);
